MODULES = ("cabinet", "bed", "storage-box", "rounded-panel", "tab-slot-coupon")


def tab_slot_profiles(spec=None, *, tool_diameter=None):
    """E1.2 coupon: slot (with the model's own relief) and upright tab notches.

    Relief uses the coupon's tool diameter unless overridden. The upright's
    tab-root inside corners also receive dog-bones: without them a round tool
    leaves root fillets that stop the shoulders seating on the receiver.
    """
    coupon = build_tab_slot(spec or TabSlotSpec())
    g = coupon.geometry()
    if tool_diameter is None:
        d = g.tool_diameter
    elif type(tool_diameter) in (int, float) and math.isfinite(tool_diameter) and tool_diameter > 0:
        d = tool_diameter
    else:
        raise ProfileError("Explicit tool diameter must be a finite positive number, got %r"
                           % (tool_diameter,))
    # Generated by the reusable joint: the upright rests on the receiver and its
    # one tab (centred, width t) enters the receiver by the engagement.
    env = coupon.blanks.parameters.resolve()
    upright = next(p for p in coupon.blanks.panels if p.stable_id == UPRIGHT).box.resolve(env)
    resting = Box((upright.lo[0], upright.lo[1], 18.0), upright.hi)
    joint = TabSlot(UPRIGHT, RECEIVER, "-z", ((100 - g.tab_width / 2 - upright.lo[0], g.tab_width),),
                    g.engagement, g.clearance)
    overrides, cuts, _ = apply_joints((joint,), {UPRIGHT: resting, RECEIVER: Box((0, 0, 0), (200, 120, 18))})
    out = []
    for p in assembly_profiles(coupon.blanks, tool_diameter=d, extra_cuts=cuts, box_overrides=overrides):
        if p.panel_id == RECEIVER and d == g.tool_diameter:
            # The E1.2 model already contains these four relief circles.
            p = replace(p, notes=("slot relief identical to the E1.2 CAD relief circles",))
        out.append(p)
    return tuple(out)


def tab_slot_carcass_profiles(sheet, *, tool_diameter, spec=None, clearance_mm=0.2, tabs_per_edge=2,
                              tab_width_mm=None):
    """A cabinet whose bottom and top tab through both sides (flush, through
    the measured side thickness) instead of butt joints. Shelves keep their
    dados; doors and back are unchanged. Geometry uses ``sheet.measured_mm``.

    Returns (profiles, joint results).
    """
    if type(sheet) is not Sheet:
        raise ProfileError("A Sheet with measured thickness is required")
    if type(tabs_per_edge) is not int or not 1 <= tabs_per_edge <= 6:
        raise ProfileError("tabs_per_edge must be 1-6")
    asm = build_cabinet(spec or CabinetSpec())
    values = {"Cab_Ply": sheet.measured_mm}
    env = asm.parameters.resolve(values)
    failed = [c.constraint_id for c, ok, _, _ in asm.check_constraints(env) if not ok]
    if failed:
        raise ProfileError("Cabinet invalid at measured thickness: " + ", ".join(failed))
    boxes = {p.stable_id: p.box.resolve(env) for p in asm.panels}
    depth = boxes["panel.bottom.001"].size[1]
    width = tab_width_mm if tab_width_mm is not None else min(120.0, depth / (2 * tabs_per_edge))
    width = float(width)
    tabs = tuple(((k + 0.5) * depth / tabs_per_edge - width / 2, width) for k in range(tabs_per_edge))
    t = sheet.measured_mm
    joints = [TabSlot(panel, side, direction, tabs, t, clearance_mm)
              for panel in ("panel.bottom.001", "panel.top.001")
              for side, direction in (("panel.left.001", "-x"), ("panel.right.001", "+x"))]
    overrides, cuts, results = apply_joints(joints, boxes)
    profiles = assembly_profiles(asm, values, tool_diameter=tool_diameter, extra_cuts=cuts,
                                 box_overrides=overrides)
    out = tuple(replace(p, notes=p.notes + (sheet.note,)) if abs(p.thickness - t) <= 1e-9 else p
                for p in profiles)
    return out, results


def module_profiles(name, *, tool_diameter, relief=True):
    if name == "cabinet":
        asm = build_cabinet(CabinetSpec())
    elif name == "bed":
        asm = build_bed_platform(BedPlatformSpec())
    elif name == "storage-box":
        asm = build_storage_box(StorageBoxSpec())
    elif name == "rounded-panel":
        asm = build_rounded_panel(RoundedPanelSpec())
    elif name == "tab-slot-coupon":
        if not relief:
            raise ValueError("The tab-slot coupon is only manufacturable with relief")
        return tab_slot_profiles(tool_diameter=tool_diameter)
    else:
        raise ValueError("Unknown module %r; choose from %s" % (name, ", ".join(MODULES)))
    return assembly_profiles(asm, tool_diameter=tool_diameter, relief=relief)
